"""Generate docs/DATA_DICTIONARY.md from the processed schemas and dictionary.yaml."""

from __future__ import annotations

from importlib import resources
from typing import Any

import duckdb
import yaml

from football_scouting.config import Config
from football_scouting.model.database import table_files

INTRO = """# Data dictionary

Generated by `make dictionary` from the processed Parquet schemas and
`src/football_scouting/model/dictionary.yaml`; do not edit by hand.

## Layers and access

- `data/raw/`: files as downloaded (StatsBomb JSON, Transfermarkt gzipped CSV).
- `data/interim/statsbomb/`: faithful Parquet copy of the StatsBomb JSON (nested columns).
- `data/processed/`: the analytical model documented here, as Parquet files under
  `statsbomb/`, `links/`, `transfermarkt/` and `profiles/` (built from the other three), plus
  `scouting.duckdb`, a DuckDB database with one view per table (Transfermarkt tables prefixed
  `tm_`).

```python
from football_scouting.config import load_config
from football_scouting.model.database import connect_readonly

con = connect_readonly(load_config())
con.sql("SELECT * FROM player_seasons JOIN player_map ON sb_player_id = player_id LIMIT 5")
```

## Conventions

- **Pitch**: 120 x 80 (yards), origin at the top-left corner; locations are a 0.1-yard grid
  (0.1 to 120.0, 0.1 to 80.0). Every event is described from the acting team's point of view,
  attacking towards x = 120 with y = 0 on its left: an event both teams record sits at (x, y)
  for one and (120.1 - x, 80.1 - y) for the other.
- **Time**: `match_seconds` is real time since kick-off. The match clock (`minute`, `second`)
  restarts at 45:00 in the second half, so it is not real time after half-time.
- **Minutes played** are real time on the pitch, stoppage time included; per-90 metrics use
  them. A player's time ends at their first exit (substitution event or dismissal, even when the
  lineup says otherwise), temporary absences are excluded, overlapping stints count once.
- **Flags**: StatsBomb only publishes boolean attributes when true; missing flags are false.
- **Names**: escaped apostrophes in StatsBomb names are undone ("N''Golo" -> "N'Golo").
- **Scouting pool**: `scouting_pool = true` for Premier League, La Liga, Serie A and Ligue 1.
  The Bundesliga data is Bayer Leverkusen's 34 matches only.
- **Snapshot columns** (Transfermarkt): values as of the 2026 snapshot, i.e. future information
  for the 2015/16 back-test. They may describe outcomes, never features.

### Position groups

| Code | Group | StatsBomb positions |
|---|---|---|
{groups}
"""


SECTION_TITLES = {
    "statsbomb": "StatsBomb tables",
    "links": "StatsBomb to Transfermarkt links",
    "transfermarkt": "Transfermarkt tables",
    "profiles": "Player profiles",
}


def load_spec() -> dict[str, Any]:
    text = resources.files("football_scouting.model").joinpath("dictionary.yaml").read_text()
    return yaml.safe_load(text)


def _schema(con: duckdb.DuckDBPyConnection, path) -> list[tuple[str, str]]:
    rel = con.sql(f"SELECT * FROM read_parquet('{path}') LIMIT 0")
    return [(c, str(t)) for c, t in zip(rel.columns, rel.types, strict=True)]


def check(cfg: Config) -> list[str]:
    """Problems: undocumented columns, documented columns that do not exist, missing tables."""
    spec, problems = load_spec(), []
    common = spec["common_event_columns"]
    files = {f"{f.parent.name}/{f.stem}": f for f in table_files(cfg).values()}
    con = duckdb.connect()
    for key in sorted(set(files) - set(spec["tables"])):
        problems.append(f"{key}: table not documented")
    for key, table in spec["tables"].items():
        if key not in files:
            problems.append(f"{key}: documented but not built")
            continue
        cols = [c for c, _ in _schema(con, files[key])]
        documented = dict(table.get("columns") or {})
        if cols[: len(common)] == list(common):
            documented = {**common, **documented}
        problems += [f"{key}.{c}: not documented" for c in cols if c not in documented]
        problems += [f"{key}.{c}: documented but missing" for c in documented if c not in cols]
    return problems


def render(cfg: Config) -> str:
    spec = load_spec()
    common = spec["common_event_columns"]
    files = {f"{f.parent.name}/{f.stem}": f for f in table_files(cfg).values()}
    con = duckdb.connect()
    groups = "\n".join(
        f"| {g.code} | {g.name} | {', '.join(map(str, g.position_ids))} |"
        for g in cfg.position_groups
    )
    out = [INTRO.format(groups=groups)]
    common_written = False
    section = None
    for key, table in spec["tables"].items():
        source, name = key.split("/")
        if source != section:
            section = source
            out.append(f"## {SECTION_TITLES[source]} (`data/processed/{source}/`)\n")
        schema = _schema(con, files[key])
        cols = [c for c, _ in schema]
        types = dict(schema)
        view = f"tm_{name}" if source == "transfermarkt" else name
        out.append(f"### `{view}`\n")
        out.append(f"{table['description'].strip()}\n")
        n = con.execute(f"SELECT count(*) FROM read_parquet('{files[key]}')").fetchone()[0]
        grain = table.get("grain", "one row per event")
        out.append(f"Grain: {grain}. Rows: {n:,}. File: `{source}/{name}.parquet`.\n")
        has_common = cols[: len(common)] == list(common)
        rows = []
        if has_common and not common_written:
            rows += [(c, types[c], common[c]) for c in common]
            common_written = True
        elif has_common:
            out.append("Starts with the common event columns (see `events`), then:\n")
        rows += [(c, types[c], d) for c, d in (table.get("columns") or {}).items()]
        if rows:
            out.append("| Column | Type | Description |\n|---|---|---|")
            out += [f"| `{c}` | `{t}` | {d} |" for c, t, d in rows]
            out.append("")
    return "\n".join(out).rstrip() + "\n"
